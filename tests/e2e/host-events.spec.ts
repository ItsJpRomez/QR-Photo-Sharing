import { expect, test } from '@playwright/test'
import { createEvent, signUpHost } from './helpers'

test('creating an event with albums and a PIN', async ({ page }) => {
  await signUpHost(page)
  await expect(page.getByText('No events yet')).toBeVisible()
  await page.getByRole('link', { name: 'Create event' }).click()
  await page.getByLabel('Event name').fill('Ana & Marco')
  await page.getByLabel('Albums (optional)').fill('Ceremony\nDance floor')
  await page.getByLabel('PIN (optional)').fill('48a21')
  await expect(page.getByLabel('PIN (optional)')).toHaveValue('4821')
  await page.getByRole('button', { name: 'Create event' }).click()
  await expect(page.getByRole('heading', { name: 'Ana & Marco' })).toBeVisible()
  await page.getByRole('link', { name: 'Albums & tags' }).click()
  await expect(page.getByRole('listitem').filter({ hasText: 'Ceremony' })).toBeVisible()
  await page.getByRole('link', { name: 'Settings' }).click()
  await expect(page.getByText('This event has a PIN')).toBeVisible()
})

test('albums can be added, renamed, reordered and deleted', async ({ page }) => {
  await signUpHost(page)
  const event = await createEvent(page, { albums: ['Ceremony', 'Dance floor'] })
  await page.goto(`/host/events/${event.id}/organize`)
  const names = () => page.getByRole('list').first().locator('li > span:first-child').allTextContents()
  await expect.poll(names).toEqual(['Ceremony', 'Dance floor'])
  await page.getByRole('button', { name: 'Move Dance floor up' }).click()
  await expect.poll(names).toEqual(['Dance floor', 'Ceremony'])
  await page.getByRole('button', { name: 'Rename Ceremony' }).click()
  await page.getByLabel('Album name').fill('The vows')
  await page.getByRole('button', { name: 'Save name' }).click()
  await expect.poll(names).toEqual(['Dance floor', 'The vows'])
  await page.getByLabel('New album').fill('Speeches')
  await page.getByRole('button', { name: 'Add album' }).click()
  await expect.poll(names).toEqual(['Dance floor', 'The vows', 'Speeches'])
  await page.getByRole('button', { name: 'Delete Dance floor' }).click()
  await expect(page.getByText('Its photos stay in the gallery.')).toBeVisible()
  await page.getByRole('button', { name: 'Delete album' }).click()
  await expect.poll(names).toEqual(['The vows', 'Speeches'])
  await page.reload()
  await expect.poll(names).toEqual(['The vows', 'Speeches'])
})

test('replacing the link warns first, then the old one stops working', async ({ page }) => {
  await signUpHost(page)
  const event = await createEvent(page)
  await page.goto(`/host/events/${event.id}/settings`)
  await page.getByRole('button', { name: 'Replace link' }).click()
  await expect(page.getByText('Printed QR codes will stop working')).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Replace link' }).click()
  await expect(page.getByText('The link is replaced')).toBeVisible()
  expect((await page.request.get(`/api/e/${event.code}`)).status()).toBe(404)
})

test('feature switches keep their state', async ({ page }) => {
  await signUpHost(page)
  const event = await createEvent(page)
  await page.goto(`/host/events/${event.id}/settings`)
  await page.getByRole('switch', { name: 'Hearts' }).click()
  await expect(page.getByRole('switch', { name: 'Hearts' })).toHaveAttribute('aria-checked', 'false')
  await page.getByRole('switch', { name: 'Close uploads' }).click()
  await expect(page.getByText('Uploads are closed.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('switch', { name: 'Hearts' })).toHaveAttribute('aria-checked', 'false')
  await expect(page.getByRole('switch', { name: 'Close uploads' })).toHaveAttribute('aria-checked', 'true')
})

test("another host's event page is not found", async ({ page, context }) => {
  await signUpHost(page)
  const event = await createEvent(page)
  await context.clearCookies()
  await signUpHost(page)
  const res = await page.goto(`/host/events/${event.id}`)
  expect(res!.status()).toBe(404)
})

test('keyboard only: the dialog opens, traps focus and closes with Escape', async ({ page, browserName }) => {
  test.skip(browserName === 'webkit', 'touch device')
  await signUpHost(page)
  const event = await createEvent(page)
  await page.goto(`/host/events/${event.id}/settings`)
  await page.getByRole('button', { name: 'Replace link' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('button', { name: 'Replace link' })).toBeFocused()
})
